    "c6029b41b3f21c1ec433b282598da243a381577ea6137021afc4f698c258fbb4")
  config.active_record.encryption.key_derivation_salt = ENV.fetch("ACTIVE_RECORD_ENCRYPTION_KEY_DERIVATION_SALT",
    "c2bd3d18a562db28bea803c40ea47e17ec9abdb2201e07ad258dce768af0ec3c")

  # Log-only N+1 surfacing via the bullet gem (development only; never raises).
  if defined?(Bullet)
    config.after_initialize do
      Bullet.enable = true
      Bullet.alert = false
      Bullet.console = false
      Bullet.bullet_logger = true
      Bullet.rails_logger = true
      Bullet.add_footer = false
    end
  end
end
