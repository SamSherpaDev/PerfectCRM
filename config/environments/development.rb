  config.active_record.encryption.primary_key = ENV.fetch("ACTIVE_RECORD_ENCRYPTION_PRIMARY_KEY",
    "7a167bcaf547cff9ca225cc68b70487024e43fa748165009293f576e9c75ff8b")
